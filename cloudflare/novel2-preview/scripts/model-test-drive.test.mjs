import assert from 'node:assert/strict';
import {modelTestDrive} from '../src/model-test-drive.js';
const env={MODEL_TESTS_DRIVE_INGEST_KEY:'test_secret_1234567890_1234567890'};
assert.throws(()=>modelTestDrive({}),/NOT_CONFIGURED/);
let calls=0;
const http=async(url,options)=>{
  calls++;
  assert.equal(url,'https://night4two-drive-oauth.kontrakevich.workers.dev/api/drive/ingest');
  assert.equal(options.method,'POST');
  assert.equal(options.headers.authorization,'Bearer '+env.MODEL_TESTS_DRIVE_INGEST_KEY);
  const b=JSON.parse(options.body);
  assert.equal(b.kind,'source');
  assert.equal(b.content,'test');
  assert.match(b.filename,/^model-test-[0-9a-f-]+-source\.txt$/);
  return Response.json({ok:true,id:'file_123456789'});
};
const job='a1b2c3d4-1111-4222-8333-123456789abc';
const drive=modelTestDrive(env,http);
const result=await drive.upload('sample.txt','text/plain',new TextEncoder().encode('test'),job,'source');
assert.equal(result.id,'file_123456789');
assert.equal(result.url,'https://drive.google.com/file/d/file_123456789/view');
assert.equal(calls,1);
await assert.rejects(()=>drive.upload('sample.txt','application/json',new TextEncoder().encode('test'),job,'source'),/DRIVE_UPLOAD_INVALID/);
let uploads=0;
const failed=modelTestDrive(env,async()=>{uploads++;throw Error('timeout')});
await assert.rejects(()=>failed.upload('sample.txt','text/plain',new Uint8Array([1]),job,'source'),/WRITE_UNCERTAIN/);
assert.equal(uploads,1);
const unauthorized=modelTestDrive(env,async()=>new Response('Unauthorized',{status:401}));
await assert.rejects(()=>unauthorized.upload('sample.txt','text/plain',new Uint8Array([1]),job,'source'),/NOT_CONFIGURED/);
console.log('MODEL_TEST_DRIVE_OK');
